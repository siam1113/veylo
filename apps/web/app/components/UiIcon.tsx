export type UiIconName = keyof typeof icons;

export function UiIcon({ name, strokeWidth = 1.75, ...props }: { name: UiIconName; title?: string } & SVGProps<SVGSVGElement>) {
  const Icon = icons[name] as ComponentType<any>;
  return <Icon strokeWidth={strokeWidth} aria-hidden="true" focusable="false" {...props} />;
}
